<p>Tailwind وUnoCSS وAtomizer هي في الجوهر مجمع وزن خفيف لقواعد CSS. توجد <code>p-4</code> في ورقة الأنماط مرة واحدة بالضبط؛ وتحمل العناصر التي تستخدمها الملايين اسم الصنف فقط، لا إعلان <code>padding: 1rem;</code> مكررًا. الداخلي = القاعدة، والخارجي = العنصر الذي تنطبق عليه.</p>
