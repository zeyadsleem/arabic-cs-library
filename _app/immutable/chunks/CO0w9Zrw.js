<p>إن كنت قد استخدمت Firestore من Firebase أو MongoDB، فسيبدو نموذج بيانات DynamoDB مألوفًا لك. والفرق الجوهري في كيفية الاستعلام عنه—إذ لا تملك DynamoDB لغة الاستعلام المرنة التي تتيحها Firestore أو MongoDB. أنت تقايض مرونة الاستعلام بأداء متوقع على أي حجم.</p>
