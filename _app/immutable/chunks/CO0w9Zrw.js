<p>هذا مجرد كائن JSON. لا توجد هجرة مخططات، ولا <code>ALTER TABLE</code>، ولا ORM. إن أردت إضافة حقل <code>priority</code> الأسبوع القادم، فما عليك إلا أن تبدأ بإدراجه في العناصر الجديدة. أما العناصر الموجودة فلن تتأثر.</p>
