<p>استخدم التفريع (أمر <code>/subtask</code>) فقط حين تعتمد المهمة على قرارات لا تستطيع إعادة صياغتها بإيجاز. وإلا فاكتب موجزًا وأرسل وكيلًا فرعيًا جديدًا. فيمكنه العمل على نموذج أرخص، وهو لا يرث افتراضاتك.</p>
