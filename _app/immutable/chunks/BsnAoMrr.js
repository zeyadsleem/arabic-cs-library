<p>في جميع الحالات، تنفّذ التعليمة <code>lea</code> عمليات حسابية على المعامل المحدّد بالمصدر S وتضع النتيجة في معامل الهدف D. والتعليمة <code>mov</code> مطابقة للتعليمة <code>lea</code> <em>إلا</em> أن التعليمة <code>mov</code> <em>ملزمة</em> بمعاملة محتويات المعامل المصدر كموقع في الذاكرة إذا كان بصيغة ذاكرة. وفي المقابل، تنفّذ <code>lea</code> الحسابات نفسها (المعقدة أحيانًا) على المعاملات <em>دون</em> البحث في الذاكرة، ما يمكّن المترجم من استخدام <code>lea</code> بذكاء كبديل لبعض أنواع العمليات الحسابية.</p>
