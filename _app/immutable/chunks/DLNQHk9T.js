<p>لتحقيق التسلسل المطلوب، نوصي باستخدام <a href="https://github.com/vercel/next.js/discussions/18172">مكون ScriptLoader for Next</a>. صُمم هذا المكون «لتحسين مسار العرض الحرج والتأكد من أن السكربتات الخارجية لا تصبح اختناقًا لتحميل الصفحة الأمثل». وأهم ميزة ذات صلة بنقاشنا هي أولويات التحميل. تتيح لنا جدولة السكربتات عند معالم مختلفة لدعم حالات استخدام مختلفة. وفيما يلي قيم أولوية التحميل المتاحة:</p>
<p><strong>After-Interactive</strong>: يحمّل سكربت 3P محددًا بعد الترطيب التالي مباشرة. يمكن استخدام ذلك لتحميل سكربتات مديري الوسوم أو الإعلانات أو التحليلات التي نريد تنفيذها في أبكر وقت ممكن، لكن بعد سكربتات 1P.</p>
<p><strong>Before-Interactive</strong>: يحمّل سكربت 3P محددًا قبل الترطيب. يمكن استخدامه عندما نريد تنفيذ سكربت 3P قبل سكربت 1P، مثل polyfill.io أو كشف الروبوتات أو الأمن والمصادقة أو إدارة موافقة المستخدم (GDPR) وغيرها.</p>
<p><strong>Lazy-Onload</strong>: يعطي أولوية لكل الموارد الأخرى على سكربت 3P المحدد، ثم يحمّله بالتحميل الكسول. يمكن استخدامه لمكونات CRM مثل Google Feedback أو سكربتات مخصصة لشبكات اجتماعية مثل المستخدمة في أزرار المشاركة والتعليقات وغيرها.</p>
<p>من ثم، يمكن أن يساعدنا الجمع بين preconnect وسمات السكربت وScriptLoader for Next.js في الحصول على التسلسل المطلوب لجميع سكربتاتنا.</p>
