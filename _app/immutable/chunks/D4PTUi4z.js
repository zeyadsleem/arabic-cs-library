<p>يعطي هذا الفصل بعض الأمثلة عن الخوارزميات العشوائية، لنكوّن فكرةً عن سببِ كَون الاحتمال مفيدًا في الحساب.
وسنرى أيضًا تقنيةَ <em>تكبير النجاح</em> (success amplification) التي تُعدّ مفتاحًا لكثيرٍ من الخوارزميات العشوائية.</p>
