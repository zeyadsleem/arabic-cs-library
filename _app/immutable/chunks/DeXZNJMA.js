<p>حدّد ما إذا كانت السلسلة المعاد ترتيبها يمكن أن تشكّل <code>t</code>. أعد <code>true</code> إن أمكن و<code>false</code> خلاف ذلك.
استخدم جدول تجزئة لتسجيل عدد مرات ظهور كل حرف. ولا ترتّب الأحرف في السلسلتين.</p>
